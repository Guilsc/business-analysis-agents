"""Generate text-only role guides from the maintained skill sources."""
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[1]


def plain(text: str) -> str:
    text = re.sub(r"\A---\n.*?\n---\n", "", text, count=1, flags=re.S)
    return re.sub(
        r"\[([^\]]+)\]\(([^)]+)\)",
        lambda m: m.group(0) if m[2].startswith(("https://", "http://")) else m[1],
        text,
    )


def render(skill: Path) -> str:
    sections = [plain((skill / "SKILL.md").read_text(encoding="utf-8"))]
    for directory in ("templates", "references"):
        for path in sorted((skill / directory).glob("*")):
            if not path.is_file():
                continue
            body = path.read_text(encoding="utf-8")
            if path.suffix == ".json":
                body = "```json\n" + body.strip() + "\n```\n"
            else:
                body = plain(body)
            sections.append("## Embedded resource: " + path.name + "\n\n" + body)
    header = (
        "<!-- Generated by scripts/build_portable.py; edit the skill source. -->\n\n"
        "Use this role in a text-only host. Embedded resources are below. Other role guides "
        "and the optional diagram-design dependency must be supplied separately when needed. "
        "Tool commands and paths do not imply that this host has execution or filesystem access.\n\n"
    )
    return header + "\n\n---\n\n".join(sections).strip() + "\n"


def main() -> None:
    output = REPO / "portable" / "roles"
    output.mkdir(parents=True, exist_ok=True)
    for skill in sorted((REPO / "skills").iterdir()):
        if (skill / "SKILL.md").is_file():
            (output / (skill.name + ".md")).write_text(render(skill), encoding="utf-8")
    print("Portable role guides regenerated")


if __name__ == "__main__":
    main()
